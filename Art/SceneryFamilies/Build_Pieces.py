def packed(points, region):
    x, y, width, height = region
    values = []
    for px, py in points:
        values.extend([(px-x)/width, (py-y)/height])
    return "PackedVector2Array(" + ", ".join(f"{value:.6f}" for value in values) + ")"


def quoted(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def write_piece(piece):
    region = piece["region"]
    lines = [
        '[gd_resource type="Resource" script_class="SceneryFamilyPiece" load_steps=3 format=3]',
        '',
        '[ext_resource type="Script" path="res://Component/SceneryFamilies/Scenery_Family_Piece.gd" id="1"]',
        f'[ext_resource type="Texture2D" path="res://Art/SceneryFamilies/Generated/{piece["source"]}.png" id="2"]',
        '', '[resource]', 'script = ExtResource("1")',
        'piece_id = &' + quoted(piece["id"]),
        'display_name = ' + quoted(piece["name"]),
        'family = &' + quoted(piece["family"]),
        'silhouette_note = ' + quoted(piece["note"]),
        'affordance_note = ' + quoted(piece["role"]),
        'parent_texture = ExtResource("2")',
        'region = Rect2(' + ', '.join(map(str, region)) + ')',
        'display_size = Vector2(' + ', '.join(map(str, piece["size"])) + ')',
        'solids = Array[PackedVector2Array]([' + ', '.join(packed(poly, region) for poly in piece["solids"]) + '])',
        'footholds = Array[PackedVector2Array]([' + ', '.join(packed(edge, region) for edge in piece["feet"]) + '])',
        'empty_points = ' + packed(piece.get("empty", []), region),
    ]
    if "picks" in piece:
        lines.append('picks = Array[PackedVector2Array]([' + ', '.join(packed(poly, region) for poly in piece["picks"]) + '])')
    destination = ROOT / 'Pieces' / (piece['id'] + '.tres')
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(piece['id'], region, piece['size'])


